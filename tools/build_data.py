#!/usr/bin/env python3
"""Build the offline edition from the readable spec and archived CUV chapters (no network)."""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
text = (ROOT/'docs/复原依据.md').read_text()
nums, entries, verses = {}, {}, {}
names = {'1ki':'列王纪上','2ch':'历代志下','ex':'出埃及记','lev':'利未记','num':'民数记','deut':'申命记'}
for file in sorted((ROOT/'data/source').glob('*.json')):
    for row in json.loads(file.read_text())['record']:
        key = f"{file.stem}:{row['sec']}"
        verses[key] = row['bible_text']
for line in text.splitlines():
    if not line.startswith('|'): continue
    a = [x.strip() for x in line.strip('|').split('|')]
    if re.fullmatch('[A-Za-z][a-zA-Z0-9]*',a[0]):
        if len(a)==3:
            n=float(a[1]); nums[a[0]]=int(n) if n.is_integer() else n
        else:
            key,name,region,tier,groups,fact,note=a
            assert key not in entries
            refs=[]
            for group in groups.split(';'):
                m=re.fullmatch(r'(1ki|2ch|ex|lev|num|deut)(\d+):(\d+)(?:-(\d+))?',group); assert m,group
                book,ch,start,end=m.groups(); ids=[f'{book}{ch}:{i}' for i in range(int(start),int(end or start)+1)]
                assert all(i in verses for i in ids), group
                refs.append(dict(title=f'{names[book]} {ch}:{start}'+(f'–{end}' if end else ''),ids=ids))
            entries[key]=dict(name=name,region=region,tier=tier,fact=fact,note=note,refs=refs)
needed=sorted({k for e in entries.values() for r in e['refs'] for k in r['ids']})
data=dict(dims=nums,entries=entries,verses={k:verses[k] for k in needed})
(ROOT/'data/edition.js').write_text('/* Generated by tools/build_data.py from docs/复原依据.md and the archived CUV. */\nwindow.EDITION = '+json.dumps(data,ensure_ascii=False,indent=1)+';\n')
print(f'{len(nums)} parameters, {len(entries)} exhibits, {len(needed)} distinct verses')
